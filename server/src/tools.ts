// The tools Claude (or any MCP client) sees. The server only describes them; the Star2D app on the phone runs them.
// Keep the descriptions short: they are sent to the model in every conversation.

type Json = Record<string, unknown>;

export interface ToolDef {
  name: string;
  description: string;
  inputSchema: Json;
  /** answered by the server itself, never forwarded to the phone */
  local?: boolean;
  /** upper bound for the phone's answer, in seconds (default 55) */
  timeout?: number;
}

const str = (description: string, extra: Json = {}): Json => ({ type: "string", description, ...extra });
const num = (description: string): Json => ({ type: "number", description });
const bool = (description: string): Json => ({ type: "boolean", description });
const anyObj = (description: string): Json => ({ type: "object", description, additionalProperties: true });
const arr = (items: Json, description: string): Json => ({ type: "array", description, items });
const obj = (properties: Record<string, Json>, required: string[] = []): Json => ({
  type: "object",
  properties,
  ...(required.length ? { required } : {}),
});
const opsOf = (description: string, ops: string[], extra: Record<string, Json> = {}, top: Record<string, Json> = {}): Json =>
  obj(
    {
      ...top,
      ops: arr(
        {
          type: "object",
          additionalProperties: true,
          properties: { op: str("operation", { enum: ops }), ...extra },
          required: ["op"],
        },
        description,
      ),
    },
    ["ops"],
  );

